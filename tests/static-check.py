#!/usr/bin/env python3
"""README §11 check 1: static check of the add-on source.

* Lists every call that can change mail (messages.move/delete/copy/update,
  folders.create, compose.sendMessage) with the functions that reach it.
* Fails if one appears outside the reviewed call sites below, or if forbidden
  things appear: alarms, timers in the background, onMoved/onDeleted listeners,
  install/startup handlers, network APIs, messages.delete, innerHTML.

Run: python3 tests/static-check.py  (writes CALL_SITES.md)
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'src'

MUTATING = re.compile(r'\b(?:api|messenger|browser)\.(messages\.(?:move|delete|copy|update|archive|import)|folders\.(?:create|delete|move|rename)|compose\.(?:sendMessage|beginNew))\s*\(')

# Reviewed call sites: (file, api call, enclosing function) -> who triggers it.
ALLOWED = {
    ('lib/mail.js', 'messages.move', 'moveItems'):
        'trashItems / moveToFolder / restore (lib/actions.js), which run only from dashboard click handlers '
        '(Trash all, Trash, Move, Restore, Restore all, Apply my Block rules…) and from background.js handleNewMail (R-BLK-2).',
    ('lib/mail.js', 'folders.create', 'ensureFolderPath'):
        'moveToFolder (lib/actions.js) ← moveNow (dashboard/common.js) ← the "Move" button click handlers on the Senders and File by person tabs.',
    ('lib/sync.js', 'compose.beginNew', 'publish'):
        'Settings tab "Publish now" click handler (dashboard/settings.js doPublish).',
    ('lib/sync.js', 'compose.sendMessage', 'publish'):
        'Settings tab "Publish now" click handler (dashboard/settings.js doPublish).',
}

FORBIDDEN = [
    (re.compile(r'\balarms\b'), 'alarms API'),
    (re.compile(r'\bonMoved\b|\bonDeleted\b|\bonCopied\b'), 'reacting to the user\'s own moves/deletions'),
    (re.compile(r'\bonInstalled\b|\bonStartup\b'), 'install/startup jobs'),
    (re.compile(r'\bsetInterval\s*\('), 'timers'),
    (re.compile(r'\bfetch\s*\(|XMLHttpRequest|WebSocket|sendBeacon|EventSource'), 'network requests'),
    (re.compile(r'messages\.delete\b'), 'messages.delete (deleting means moving to Trash)'),
    (re.compile(r'\.innerHTML\b|insertAdjacentHTML|document\.write'), 'HTML injection of email content'),
    (re.compile(r'\beval\s*\(|new Function\s*\('), 'eval'),
]

def enclosing_function(lines, idx):
    pat = re.compile(r'^\s*(?:export\s+)?(?:async\s+)?function\s*\*?\s*(\w+)|^\s*(?:export\s+)?const\s+(\w+)\s*=\s*(?:async\s*)?\(')
    for j in range(idx, -1, -1):
        m = pat.match(lines[j])
        if m:
            return m.group(1) or m.group(2)
    return '?'

def strip_comment(line):
    return re.sub(r'//.*$', '', line)

def main():
    problems, sites = [], []
    for path in sorted(SRC.rglob('*.js')):
        rel = path.relative_to(SRC).as_posix()
        lines = path.read_text(encoding='utf-8').splitlines()
        for i, raw in enumerate(lines):
            line = strip_comment(raw)
            for m in MUTATING.finditer(line):
                call = m.group(1)
                fn = enclosing_function(lines, i)
                key = (rel, call, fn)
                sites.append((rel, i + 1, call, fn, ALLOWED.get(key)))
                if key not in ALLOWED:
                    problems.append(f'{rel}:{i+1}: unreviewed mail-changing call {call} in {fn}()')
            for pat, why in FORBIDDEN:
                if pat.search(line):
                    problems.append(f'{rel}:{i+1}: forbidden ({why}): {raw.strip()}')
    # Background: the only listeners allowed.
    bg = (SRC / 'background.js').read_text(encoding='utf-8')
    listeners = sorted(set(re.findall(r'(\w+\.\w+)\.addListener', bg)))
    expected = ['action.onClicked', 'menus.onClicked', 'messages.onNewMailReceived', 'tabs.onRemoved']
    if listeners != expected:
        problems.append(f'background.js listeners {listeners} != reviewed {expected}')
    # Manifest permissions.
    import json
    perms = json.loads((SRC / 'manifest.json').read_text())['permissions']
    allowed_perms = {'accountsRead', 'accountsFolders', 'messagesRead', 'messagesMove', 'storage', 'menus', 'compose', 'compose.send'}
    extra = set(perms) - allowed_perms
    if extra:
        problems.append(f'manifest requests unreviewed permissions: {sorted(extra)}')

    out = ['# Mail-changing call sites', '',
           'Generated by `tests/static-check.py` (README §11, check 1). Every call that can move, delete, copy, flag or send mail:', '',
           '| File:line | Call | In function | Reached from |', '|---|---|---|---|']
    for rel, ln, call, fn, why in sites:
        out.append(f'| `src/{rel}:{ln}` | `{call}` | `{fn}()` | {why or "**UNREVIEWED**"} |')
    out += ['', f'Background listeners: {", ".join(listeners)}. No alarms, no onMoved/onDeleted, no install/startup jobs, no network APIs.', '']
    (ROOT / 'CALL_SITES.md').write_text('\n'.join(out), encoding='utf-8')

    for rel, ln, call, fn, why in sites:
        print(f'  src/{rel}:{ln}  {call}  in {fn}()')
    if problems:
        print('\nSTATIC CHECK FAILED:')
        for p in problems:
            print('  ' + p)
        sys.exit(1)
    print(f'\nstatic check passed ({len(sites)} reviewed call sites; background listeners: {", ".join(listeners)})')

if __name__ == '__main__':
    main()
